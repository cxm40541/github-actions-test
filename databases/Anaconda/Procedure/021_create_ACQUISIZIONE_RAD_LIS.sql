--*************************************************************************
--           CONTROLLO 5
--*************************************************************************

IF @FLAGANAG <> '0' AND (@COGNOME = '' OR @COGNOME IS NULL)
BEGIN
	SELECT  @COGNOME = LSRTIT_COGNOME , @NOME = LSRTIT_NOME
	FROM LSRTIT
	WHERE LSRTIT_KEY_ID_RICEV=@RICEV 
		AND LSRTIT_KEY_DATA_INS = @FKDATAINSTIT
		AND LSRTIT_KEY_ORA_INS = @FKORAINSTIT

END 


--*************************************************************************
--           IL RECORD VIENE INSERITO SU LSRRAD_LIS
--*************************************************************************
INSERT INTO LSRRAD_LIS VALUES (
	@RICEV, 		
	@DATAOGGI,
	@ORAOGGI,
	@CATEGORIA,		
	@SERVIZIO,		
	@ATTIVITA,	
	@TIPOMOVIMENTAZIONE,
	@FONTE,  
	@FIRMADOC,	
	@NOMEFILE,			
	@DATADOC,		
	@DATAINVIODOC,	
	@NUMPROTDOC,	
	@ASSOCIAZIONE,	
	@CAUSALE,
	@STATODOC,	
	@COGNOME,	
	@NOME	,	
	@NOTE,	
	@FLAGANAG,	
	@FKDATAINSTIT,	
	@FKORAINSTIT,	
	@FIRMA	)

IF @@ERROR <> 0 
BEGIN
	SELECT @MSGERR = '9999 - ' + @RICEV +' ERRORE INSERIMENTO RAD - RAD NON ACQUISITO'
	RETURN
END
ELSE
BEGIN
	IF @FLAGANAG = '0'
	BEGIN
		SELECT @MSGERR = '9999 - ' + @RICEV +' RAD ACQUISITO MA NON ABBINATO'
	END
	ELSE	
	BEGIN	
		SELECT @MSGERR = '9999 - ' + @RICEV +'RAD  ACQUISITO CORRETTAMENTE'
	END
	RETURN
END
GO
