CREATE      PROCEDURE [dbo].[VARIAZIONE_NULLA_OSTA_GS]
	@RICEV 			CHAR(6),
	@NOMEFILE			VARCHAR(255),
	@DATA_DOC			CHAR(8),
	@CODICESERVIZIO CHAR(2),
	@DATA_INVIO_DOC		CHAR(8),
	@NUMPROTDOC		CHAR(25),
	@COGNOME			CHAR(24),
	@NOME			CHAR(20),
	@DATAACCETTAZIONE	CHAR(8),
	@DATAREVOCA		CHAR(8),
	@NUM_CONC_SCOMMESSE	CHAR(10),
	@DATA_CONC_SCOMMESSE	CHAR(8),
	@NUM_AUTORIZZAZIONE	CHAR(10),
	@RIL_AUTORIZZAZIONE	CHAR(20),
	@NUM_CONCESSIONE		CHAR(6),
	@STATODOC			CHAR(1),
	@NOTE			CHAR(100),
	@FLAGANAG			CHAR(1),
	@FKDATAINSTIT		CHAR(8),
	@FKORAINSTIT		CHAR(8),

	@KEYDATAINSDOC	CHAR(8),
	@KEYORAINSDOC	CHAR(8),
	@ABBINATO 		CHAR(1),

	@FIRMA			CHAR(17),
	@MSGERR			VARCHAR(100) OUTPUT
 AS



DECLARE 	@APPORICEV		CHAR(6),
		@CHKRICEV		CHAR(6),
		@APPODATA		CHAR(8),
		@DATAOGGI   		CHAR(8),
		@ORAOGGI  		CHAR(8),
		@COGNOMETIT	CHAR(24),
		@NOMETIT		CHAR(20),
		@FLAGANAGTIT	CHAR(1),
		@DATAINSTIT		CHAR(8),
		@ORAINSTIT		CHAR(8),
		@TIPOPREC 		CHAR(1),
		@TIPOPROVV		CHAR(1),
		@TITTROVATO	CHAR(1),
		@FLAGOK 		CHAR(1)


SELECT @DATAOGGI = CONVERT (VARCHAR(10), GETDATE(),112)
SELECT @ORAOGGI =
	SUBSTRING(CONVERT (VARCHAR(22), GETDATE(),121),12,2)+
 	SUBSTRING(CONVERT (VARCHAR(22), GETDATE(),121),15,2)+
 	SUBSTRING(CONVERT (VARCHAR(22), GETDATE(),121),18,2)+
 	SUBSTRING(CONVERT (VARCHAR(22), GETDATE(),121),21,2)


--EFFETTUO I SEGUENTI CONTROLLI:
-- 1) SE IL ABBINATO = '0' E FLAGANAG è <>0 VERIFICO CHE NON SIA GIà PRESENTE UN NULLA OSTA PER IL RICEVITORE E LA RICEVITORIA IN QUESTIONE
-- 2) SE IL NOME/COGNOME NON è VALORIZZATO, MA è VALORIZZATO LA FK DEL TIT, PRENDO I VALORI DA LSRTIT


SELECT @CHKRICEV = NULL

SELECT @CHKRICEV = LSRTIT_CONI_KEY_ID_RICEV FROM LSRTIT_CONI
WHERE LSRTIT_CONI_KEY_ID_RICEV = @RICEV

IF @CHKRICEV IS NULL

BEGIN
	SELECT @MSGERR = '8888 - ' + @RICEV +' RICEVITORIA INESISTENTE'
	RETURN
END

IF LTRIM(RTRIM(@DATAACCETTAZIONE)) = ''
BEGIN
	SELECT @DATAACCETTAZIONE = NULL  
END 



--*************************************************************************
--           STEP 1
--*************************************************************************

SELECT @APPORICEV = NULL

IF (@ABBINATO = '0' AND @FLAGANAG <> '0')
BEGIN
	SELECT @APPORICEV = LSRNUO_GS_KEY_ID_RICEV 
	FROM LSRNUO_GS
	WHERE LSRNUO_GS_KEY_ID_RICEV = @RICEV
		AND LSRNUO_GS_FK_DATA_INS_TIT = @FKDATAINSTIT
		AND LSRNUO_GS_FK_ORA_INS_TIT = @FKORAINSTIT
		AND LSRNUO_GS_CODICE_SERVIZIO = @CODICESERVIZIO
	
	IF (@APPORICEV <>'' OR @APPORICEV IS NOT NULL)
	BEGIN
		SELECT @MSGERR = '9999 - ' + @RICEV +' PER LA RIC. ESISTE UN NULLA OSTA CON STESSO TITOLARE - NULLA OSTA NON ACQUISITO'
		RETURN
	END
END

 
--*************************************************************************
--          STEP 2
--*************************************************************************

IF @FLAGANAG <> '0' AND (@COGNOME = '' OR @COGNOME IS NULL)
BEGIN
	SELECT  @COGNOME = LSRTIT_CONI_COGNOME , @NOME = LSRTIT_CONI_NOME
	FROM LSRTIT_CONI
	WHERE LSRTIT_CONI_KEY_ID_RICEV=@RICEV 
		AND LSRTIT_CONI_KEY_DATA_INS = @FKDATAINSTIT
		AND LSRTIT_CONI_KEY_ORA_INS = @FKORAINSTIT

END 


--*************************************************************************
--           CONTROLLO 3
--*************************************************************************

IF @FLAGANAG <> '0' 
BEGIN
	SELECT  @FLAGANAG = LSRTIT_CONI_FLAG_ANAG
	FROM LSRTIT_CONI
	WHERE LSRTIT_CONI_KEY_ID_RICEV=@RICEV 
		AND LSRTIT_CONI_KEY_DATA_INS = @FKDATAINSTIT
		AND LSRTIT_CONI_KEY_ORA_INS = @FKORAINSTIT

END 

IF @FLAGANAG = '0' 
BEGIN
	SELECT @FKDATAINSTIT = NULL	
	SELECT @FKORAINSTIT = NULL	
END


--*************************************************************************
--           STEP 4
--*************************************************************************
UPDATE LSRNUO_GS 
SET
	--LSRNUO_GS_key_data_ins = @DATAOGGI, 
	--LSRNUO_GS_key_ora_ins = @ORAOGGI, 
	LSRNUO_GS_codice_servizio = @CODICESERVIZIO,
	LSRNUO_GS_data_nulla_osta = @DATA_DOC, 
	LSRNUO_GS_data_invio = @DATA_INVIO_DOC, 
	LSRNUO_GS_num_prot = @NUMPROTDOC, 
	LSRNUO_GS_data_accettazione = @DATAACCETTAZIONE,
	LSRNUO_GS_data_revoca = @DATAREVOCA,
	LSRNUO_GS_stato = @STATODOC, 
	LSRNUO_GS_cognome = @COGNOME, 
	LSRNUO_GS_nome = @NOME, 
	LSRNUO_GS_num_conc_scommesse = @NUM_CONC_SCOMMESSE, 
	LSRNUO_GS_data_conc_scommesse = @DATA_CONC_SCOMMESSE, 
	LSRNUO_GS_num_autorizzazione = @NUM_AUTORIZZAZIONE, 
	LSRNUO_GS_ril_autorizzazione = @RIL_AUTORIZZAZIONE, 
	LSRNUO_GS_num_concessione = @NUM_CONCESSIONE, 
	LSRNUO_GS_note = @NOTE, 
	LSRNUO_GS_flag_anag = @FLAGANAG, 
	LSRNUO_GS_fk_data_ins_tit = @FKDATAINSTIT, 
	LSRNUO_GS_fk_ora_ins_tit = @FKORAINSTIT, 
	LSRNUO_GS_firma = @FIRMA
WHERE LSRNUO_GS_KEY_ID_RICEV = @RICEV
	AND LSRNUO_GS_KEY_DATA_INS = @KEYDATAINSDOC
	AND LSRNUO_GS_KEY_ORA_INS = @KEYORAINSDOC

IF @@ERROR <> 0 
BEGIN
	SELECT @MSGERR = '9999 - ' + @RICEV +' ERRORE INSERIMENTO NULLA OSTA - DOC. NON ACQUISITO'
	RETURN
END
ELSE
BEGIN
	SELECT @MSGERR = '9999 - ' + @RICEV +' NULLA OSTA VARIATO CORRETTAMENTE'
END
GO
