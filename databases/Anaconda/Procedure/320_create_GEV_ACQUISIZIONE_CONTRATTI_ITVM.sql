-------------------------------------------------------------
-- CONTROLLO SE GIA' ESISTE UN QUESTIONARIO PER QUEL CONTRAENTE
-------------------------------------------------------------

SELECT @RICEAPPO = ''
SELECT @MSGERR = NULL

SELECT @COGNOMEOLD = ''
SELECT @NOMEOLD = NULL



IF ISNUMERIC(LTRIM(RTRIM(@CODLTM) )) = 1
BEGIN
	SELECT @COGNOMEOLD = LSRCON_ITVM_COGNOME, @NOMEOLD = LSRCON_ITVM_NOME
	FROM LSRCON_ITVM
	WHERE LSRCON_ITVM_KEY_ID_RICEV = @CODSGI
		AND lsrcon_ITVM_fk_data_ins_tit_gev = @FKDATAINSTITGEV
		AND lsrcon_ITVM_fk_ora_ins_tit_GEV = @FKORAINSTITGEV

	IF @@ROWCOUNT > 0
	BEGIN
		SELECT @MSGERR = '9 - ESISTE GIA UN CONTRATTO INTESTATO A: ' + @COGNOME + ' ' + @NOME
		RAISERROR (@MSGERR, 16, 1)
		RETURN
	END
END
ELSE
BEGIN
	SELECT @COGNOMEOLD = LSRCON_ITVM_COGNOME, @NOMEOLD = LSRCON_ITVM_NOME
	FROM LSRCON_ITVM
	WHERE LSRCON_ITVM_KEY_ID_RICEV = @CODSGI
		AND lsrcon_ITVM_fk_data_ins_tit = @FKDATAINSTIT
		AND lsrcon_ITVM_fk_ora_ins_tit = @FKORAINSTIT

	IF @@ROWCOUNT > 0
	BEGIN
		SELECT @MSGERR = '9 - ESISTE GIA UN CONTRATTO INTESTATO A: ' + @COGNOME + ' ' + @NOME
		RAISERROR (@MSGERR, 16, 1)
		RETURN
	END
END



--------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
-- IMPOSTO IL TIPO DI ASSOCIAZIONE TRA DOCUMENTO E CONTRAENTE (SOLO PER ACQUISIZIONE DA FILE)
--------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------

IF @TIPOACQ = 'F'
BEGIN
	SELECT @MSGERR = NULL
	SELECT @FLGANAG = NULL
	SELECT @FKDATAINSTIT = NULL
	SELECT @FKORAINSTIT = NULL
	SELECT @FKDATAINSTITGEV = null
	SELECT @FKORAINSTITGEV = null

	EXEC GEV_ESISTE_RICEVITORIA @CODLTM OUTPUT, @CODAMM OUTPUT, @CODSGI OUTPUT
	SET @MSGERR = @@ERROR
	
	IF @MSGERR <> 0
	BEGIN
		RAISERROR (@MSGERR, 16, 1)
		RETURN
	END

	IF ISNUMERIC(LTRIM(RTRIM(@CODLTM) )) = 1	
		EXEC GEV_ASSOCIA_TITOLARE_DOCUMENTO_CONI @CODLTM, @COGNOME, @NOME, @FLGANAG OUTPUT, @FKDATAINSTITGEV OUTPUT, @FKORAINSTITGEV OUTPUT
	
	ELSE	
		EXEC GEV_ASSOCIA_TITOLARE_DOCUMENTO @CODLTM, @COGNOME, @NOME, @FLGANAG OUTPUT, @FKDATAINSTIT OUTPUT, @FKORAINSTIT OUTPUT

	SET @MSGERR = @@ERROR
	
	IF @MSGERR <> 0
	BEGIN
		RAISERROR (@MSGERR, 16, 1)
		RETURN
	END
END

SELECT @RICEAPPO = NULL
SELECT @FLGANAGOLD = NULL
SELECT @MSGERR = NULL

SELECT @FLGANAGOLD = LSRCON_ITVM_FLAG_ANAG
FROM LSRCON_ITVM
WHERE LSRCON_ITVM_KEY_ID_RICEV = @CODSGI
AND LSRCON_ITVM_FLAG_ANAG = @FLGANAG

IF @FLGANAGOLD IS NOT NULL
BEGIN

	IF @FLGANAG = '0'
	BEGIN
		SELECT @MSGERR = '9 - ESISTE GIA UN DOCUMENTO NON ASSOCIATO'
		RAISERROR (@MSGERR, 16, 1)
		RETURN
	END
	ELSE IF @FLGANAG = '1'
	BEGIN		SELECT @MSGERR = '9 - ESISTE GIA UN DOCUMENTO ASSOCIATO AL TITOLARE ATTUALE'
		RAISERROR (@MSGERR, 16, 1)
		RETURN
	END
	ELSE IF @FLGANAG = '2' 
	BEGIN
		SELECT @MSGERR = '9 - ESISTE GIA UN DOCUMENTO ASSOCIATO AD UN TITOLARE PRECEDENTE'		RAISERROR (@MSGERR, 16, 1)
		RETURN
	END
END	
ELSE
BEGIN


	IF @FLGANAG = '0'
	BEGIN

		SELECT @FKDATAINSTIT = NULL
		SELECT @FKORAINSTIT = NULL
		SELECT @FKDATAINSTITGEV = null
		SELECT @FKORAINSTITGEV = null
		SELECT @MSGERR = '0 - DOCUMENTO NON ASSOCIATO AD ALCUN TITOLARE'
		RAISERROR (@MSGERR, 16, 1)
	END
	ELSE IF @FLGANAG = '1'
	BEGIN
		SELECT @MSGERR = '0 - DOCUMENTO ASSOCIATO AL TITOLARE ATTUALE'
		RAISERROR (@MSGERR, 16, 1)
	END
	ELSE IF @FLGANAG >= '2' 
	BEGIN
		SELECT @MSGERR = '0 - DOCUMENTO ASSOCIATO AD UN TITOLARE PRECEDENTE'
		RAISERROR (@MSGERR, 16, 1)
	END

END

