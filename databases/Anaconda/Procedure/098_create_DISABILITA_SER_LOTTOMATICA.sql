@TIPOPROVV		CHAR(1),
@NUMPROVV		CHAR(8),
@FIRMA		CHAR(17),
@OGGI			CHAR(8),
@NUMERR 		VARCHAR(4) OUTPUT,
@MSGERR 		VARCHAR(50) OUTPUT

AS

DECLARE	

@ASSOCIAZIONE	CHAR(1),
@STATO		CHAR(1),
@CANONE		CHAR(1),
