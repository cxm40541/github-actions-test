SELECT @NOTE = 'SERVIZIO DISABILITATO DAL PROVVEDIMENTO LOTTO N° ' + @NUMPROVV + ' DEL ' + LTRIM(RTRIM(SUBSTRING(@DATAPROVV,7,2) + '-' + SUBSTRING(@DATAPROVV,5,2)+ '-' + SUBSTRING(@DATAPROVV,1,4)))
SELECT @DATA = CONVERT(CHAR,GETDATE(),112)
SELECT @ORA = SUBSTRING(CONVERT(CHAR,GETDATE(),121),12,2) + 
		SUBSTRING(CONVERT(CHAR,GETDATE(),121),15,2) +
		SUBSTRING(CONVERT(CHAR,GETDATE(),121),18,2) +
		SUBSTRING(CONVERT(CHAR,GETDATE(),121),21,2)

SELECT @DATAINSLET = @DATA

--MODIFICA DEL 15/05/2001
IF @DATADECOR <= @DATA
BEGIN
	SELECT @DATADECOR = CONVERT(CHAR,GETDATE() + 1,112)
END
--FINE MODIFICA

--MODIFICA DEL 10/05/2002 f.giacovazzi
IF @DATADECOR > CONVERT(CHAR,GETDATE() + 1,112)
BEGIN
	SELECT @DATAINSLET = CONVERT(CHAR,CONVERT(DATETIME,@DATADECOR)-1,112)
END
--FINE MODIFICA

--- TRATTAMENTO SERVIZIO F101

SELECT @STATO = NULL

SELECT @ASSOCIAZIONE=LSRSER_F101_ASSOCIAZIONE,@STATO=LSRSER_F101_STATO
FROM LSRSER_F101
WHERE LSRSER_F101_KEY_ID_RICEV = @RICEVITORIA
AND LSRSER_F101_DATA_DECOR =
(
	SELECT MAX(LSRSER_F101_DATA_DECOR) 
	FROM LSRSER_F101
	WHERE LSRSER_F101_DATA_DECOR <= @OGGI
	AND LSRSER_F101_FLAG_VALIDITA = 'Y'
	AND LSRSER_F101_KEY_ID_RICEV = @RICEVITORIA
)
AND LSRSER_F101_FLAG_VALIDITA = 'Y'

--MODIFICA DEL 31/07/2001
IF @STATO IS NOT NULL
--FINE MODIFICA DEL 31/07/2001
BEGIN
	--MODIFICA DEL 01/06/2001
	IF @STATO <>  '0'
	--FINE MODIFICA DEL 01/06/2001
	BEGIN
		INSERT INTO LSRSER_F101 VALUES
		(@RICEVITORIA,@DATAINS,@ORAINS,'2',@DATADECOR,
		@TIPOPROVV,@DATAPROVV,@NUMPROVV,@ASSOCIAZIONE,@FIRMA,@NOTE,'00000000','Y')

		IF @@ERROR <> 0 
		BEGIN
			SELECT @NUMERR = '9999'
			SELECT @MSGERR = @NUMERR + ' -  ERRORE IN INSERIMENTO LSRSER_F101'
			ROLLBACK TRANSACTION
			RETURN
		END
		ELSE
		BEGIN
			UPDATE LSRSER_F101 SET
			LSRSER_F101_FLAG_VALIDITA = 'N'
			WHERE LSRSER_F101_KEY_ID_RICEV = @RICEVITORIA
			AND LSRSER_F101_DATA_DECOR > @OGGI
			AND LSRSER_F101_DATA_DECOR <> @DATADECOR

			IF @@ERROR <> 0 
			BEGIN
				SELECT @NUMERR = '9999'
				SELECT @MSGERR = @NUMERR + ' -  ERRORE IN AGGIORNAMENTO LSRSER_F101'
				ROLLBACK TRANSACTION
				RETURN
			END
			ELSE
			BEGIN
				--MODIFICA DEL 22/06/2001: 
				--SE DISATTIVO E IL SERVIZIO è ATTIVO DEVO INVIARE LA LETTERA 
				IF @STATO = '1'
				BEGIN
					INSERT INTO LSRLET VALUES
					(@RICEVITORIA,@DATAINSLET,@ORA,'02','D',@DATADECOR,'LSRPRO',
					@DATAINS+@ORAINS,'00000000','',@FIRMA,'V')

					IF @@ERROR <> 0 
					BEGIN
						SELECT @NUMERR = '9999'
						SELECT @MSGERR = @NUMERR + ' -  ERRORE IN INSERIMENTO LSRLET'
						ROLLBACK TRANSACTION
						RETURN
					END
				END
				ELSE
				BEGIN
					--SE DISATTIVO E IL SERVIZIO è GIà DISATTIVO, NON DEVO INVIARE LA LETTERA PERCHè IL CAMBIAMENTO DI STATO è DOVUTO A CAMBIAMENTO DEL LOTTO
					INSERT INTO LSRLET VALUES
					(@RICEVITORIA,@DATAINSLET,@ORA,'02','D',@DATADECOR,'LSRPRO',
					@DATAINS+@ORAINS,'19000101','',@FIRMA,'V')

					IF @@ERROR <> 0 
					BEGIN
						SELECT @NUMERR = '9999'
						SELECT @MSGERR = @NUMERR + ' -  ERRORE IN INSERIMENTO LSRLET'
						ROLLBACK TRANSACTION
						RETURN
					END
				END
			END
		END
	END
END

