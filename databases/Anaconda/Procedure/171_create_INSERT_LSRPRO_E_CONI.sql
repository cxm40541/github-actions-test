	AND LSRNUO_CONI_FLAG_ANAG = '1'

UPDATE LSRQST_CONI
SET LSRQST_CONI_FK_DATA_INS_TIT = @OGGI,
	LSRQST_CONI_FK_ORA_INS_TIT = @ORAINS
