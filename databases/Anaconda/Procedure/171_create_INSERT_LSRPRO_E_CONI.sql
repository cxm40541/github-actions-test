SET lsrcon_GS_FK_DATA_INS_TIT = @OGGI,
	lsrcon_GS_FK_ORA_INS_TIT = @ORAINS
WHERE lsrcon_GS_KEY_ID_RICEV = @RICEVITORIA
	AND lsrcon_GS_FLAG_ANAG  = '1'

UPDATE lsrnuo_GS
SET lsrnuo_GS_FK_DATA_INS_TIT = @OGGI,
	lsrnuo_GS_FK_ORA_INS_TIT = @ORAINS
WHERE lsrnuo_GS_KEY_ID_RICEV = @RICEVITORIA
	AND lsrnuo_GS_FLAG_ANAG  = '1'

UPDATE lsrrad_GS
SET lsrrad_GS_FK_DATA_INS_TIT = @OGGI,
	lsrrad_GS_FK_ORA_INS_TIT = @ORAINS
WHERE lsrrad_GS_KEY_ID_RICEV = @RICEVITORIA
	AND lsrrad_GS_FLAG_ANAG  = '1'

UPDATE lsrtlp_GS
SET lsrtlp_GS_FK_DATA_INS_TIT = @OGGI,
	lsrtlp_GS_FK_ORA_INS_TIT = @ORAINS
WHERE lsrtlp_GS_KEY_ID_RICEV = @RICEVITORIA
	AND lsrtlp_GS_FLAG_ANAG  = '1'

----------------------------------------------------------------------------------------------------------------------
---------------------------- CONTRATTI  GIOCHI PUBBLICI -----------------------------------
----------------------------------------------------------------------------------------------------------------------

UPDATE lsrcon_GP
SET lsrcon_GP_FK_DATA_INS_TIT = @OGGI,
	lsrcon_GP_FK_ORA_INS_TIT = @ORAINS
WHERE lsrcon_GP_KEY_ID_RICEV = @RICEVITORIA
	AND lsrcon_GP_FLAG_ANAG  = '1'


UPDATE LSRFID_GP
SET LSRFID_GP_FK_DATA_INS_TIT = @OGGI,
	LSRFID_GP_FK_ORA_INS_TIT = @ORAINS
WHERE LSRFID_GP_KEY_ID_RICEV = @RICEVITORIA
	AND LSRFID_GP_FLAG_ANAG  = '1'




IF ISNUMERIC(LTRIM(RTRIM(@RICEVITORIA) )) = 1
BEGIN
	UPDATE LSRCON_GEV 
	SET LSRCON_GEV_FK_DATA_INS_TIT_GEV = @OGGI,
		LSRCON_GEV_FK_ORA_INS_TIT_GEV =@ORAINS
	WHERE LSRCON_GEV_COD_LOTTO = @RICEVITORIA
		AND LSRCON_GEV_FLAG_ANAG = '1'
	IF @@ERROR<>0
	BEGIN
		ROLLBACK TRANSACTION
		SELECT @MSGERR = 'NOK - ERRORE IN UPDATE LSRCON_GEV'
		RETURN
	END

	-- LSRQST_GEV
	UPDATE LSRQST_GEV 
	SET LSRQST_GEV_FK_DATA_INS_TIT_GEV = @OGGI,
		LSRQST_GEV_FK_ORA_INS_TIT_GEV = @ORAINS
	WHERE LSRQST_GEV_COD_LOTTO = @RICEVITORIA
		AND LSRQST_GEV_FLAG_ANAG = '1'
	IF @@ERROR<>0
	BEGIN
		ROLLBACK TRANSACTION
		SELECT @MSGERR = 'NOK - ERRORE IN UPDATE LSRQST_GEV'
		RETURN
	END

	-- LSRFID_GEV
	UPDATE LSRFID_GEV 
	SET LSRFID_GEV_FK_DATA_INS_TIT_GEV = @OGGI,
		LSRFID_GEV_FK_ORA_INS_TIT_GEV = @ORAINS
	WHERE LSRFID_GEV_COD_LOTTO = @RICEVITORIA
