	AND LSRQST_CONI_FLAG_ANAG = '1'

UPDATE LSRRAD_CONI
SET LSRRAD_CONI_FK_DATA_INS_TIT = @OGGI,
	LSRRAD_CONI_FK_ORA_INS_TIT = @ORAINS
WHERE LSRRAD_CONI_KEY_ID_RICEV = @RICEVITORIA
	AND LSRRAD_CONI_FLAG_ANAG = '1'

UPDATE LSRRIN_CONI
SET LSRRIN_CONI_FK_DATA_INS_TIT = @OGGI,
	LSRRIN_CONI_FK_ORA_INS_TIT = @ORAINS
WHERE LSRRIN_CONI_KEY_ID_RICEV = @RICEVITORIA
	AND LSRRIN_CONI_FLAG_ANAG = '1'


UPDATE LSRTLP_ST
SET LSRTLP_ST_FK_DATA_INS_TIT = @OGGI,
	LSRTLP_ST_FK_ORA_INS_TIT = @ORAINS
