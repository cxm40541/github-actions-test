	IF @@ERROR<>0
	BEGIN
		ROLLBACK TRANSACTION
		SELECT @MSGERR = 'NOK - ERRORE IN UPDATE LSRFID_GEV'
		RETURN
	END

	-- LSRRAD_GEV
	UPDATE LSRRAD_GEV 
	SET LSRRAD_FK_DATA_INS_TIT_GEV = @OGGI,
		LSRRAD_FK_ORA_INS_TIT_GEV = @ORAINS
	WHERE LSRRAD_COD_LOTTO = @RICEVITORIA
	AND LSRRAD_FLAG_ANAG = '1'
	IF @@ERROR<>0
	BEGIN
		ROLLBACK TRANSACTION
		SELECT @MSGERR = 'NOK - ERRORE IN UPDATE LSRRAD_GEV'
