BEGIN
	UPDATE LSRSER_TEL SET
	LSRSER_TEL_FLAG_VALIDITA = 'A', 
	LSRSER_TEL_KEY_DATA_INS = @DATAINS,
	LSRSER_TEL_KEY_ORA_INS = @ORAINS,
	LSRSER_TEL_NOTE = @NOTE,
	LSRSER_TEL_FIRMA = @FIRMANEW
