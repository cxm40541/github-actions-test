	lsrlet_key_id_ricev, [lsrlet_cod_amm], [lsrlet_cognome], [lsrlet_nome], [lsrlet_cod_servizio], [lsrlet_tipo_movimentazione], [lsrlet_data_decor], [lsrlet_num_prot_documento], [lsrlet_data_prot_documento], [lsrlet_destinatario], 'MF', [lsrlet_causale], [lsrlet_data_ins] 
	FROM [Anaconda].[dbo].[lsrlet_appoggio]
	WHERE substring(lsrlet_cod_amm,1,2) in ('AO','TS','UD','GO','PN','CA','SS','NU','OR','CI','OT','VS', 'OG'  )
	AND LSRLET_KEY_ID_RICEV NOT IN (SELECT LSRLET_KEY_ID_RICEV FROM LSRLET WHERE LSRLET_COD_DESTINATARIO='MF')
	and lsrlet_cod_destinatario not in  ('1','',' ')

	insert into lsrlet_appoggio  
	select distinct lsrlet_key_id_ricev, [lsrlet_cod_amm], [lsrlet_cognome], [lsrlet_nome], [lsrlet_cod_servizio], [lsrlet_tipo_movimentazione], [lsrlet_data_decor], [lsrlet_num_prot_documento], [lsrlet_data_prot_documento], 'R' lsrlet_destinatario,
	 case substring(lsrlet_cod_amm,1,2) 
	when'SS'then'CA'
	when'OR'then'CA'
	when'CA'then'CA'
	when'NU'then'CA'
	when'CI'then'CA'
	when'OT'then'CA'
	when'VS'then 'CA' 
	when'OG'then'CA'
	when'UD'then'TS'
	when'TS'then'TS'
	when'GO'then'TS'
	when'PN'then'PN'
	when'AO'then'AO'
	else substring(lsrlet_cod_amm,1,2)
	end lsrlet_cod_destinatario, [lsrlet_causale], [lsrlet_data_ins] 
	FROM [Anaconda].[dbo].[lsrlet_appoggio] a
	where LSRLET_KEY_ID_RICEV IN (SELECT distinct  LSRLET_KEY_ID_RICEV FROM LSRLET_appoggio WHERE LSRLET_COD_DESTINATARIO in ('1','',' ','MF')
	and  LSRLET_KEY_ID_RICEV not in (SELECT LSRLET_KEY_ID_RICEV FROM LSRLET_appoggio WHERE LSRLET_COD_DESTINATARIO in  ('CA','TS','AO'))
	and lsrlet_cod_destinatario not in  ('CA','TS','AO')
	and substring(lsrlet_cod_amm,1,2) in ('AO','TS','UD','GO','PN','CA','SS','NU','OR','CI','OT','VS', 'OG'  ))
	and (lsrlet_num_prot_documento in (select max(lsrlet_num_prot_documento) from lsrlet_appoggio b where b.lsrlet_key_id_ricev=a.lsrlet_key_id_ricev) or lsrlet_num_prot_documento is null)

END
